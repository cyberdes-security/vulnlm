#!/usr/bin/env bash
# Idempotent local Docker installation. Never sources .env or removes volumes.
set -euo pipefail
cd -- "$(CDPATH='' cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"

timeout=1800
check_only=0
gpu=auto
usage='Usage: bash scripts/install.sh [--check] [--gpu auto|cpu|nvidia] [--timeout SECONDS]'
while [ "$#" -gt 0 ]; do
    case "$1" in
        --check) check_only=1; shift ;;
        --gpu)
            [ "$#" -ge 2 ] || { echo "$usage" >&2; exit 2; }
            gpu=$2; shift 2 ;;
        --timeout)
            [ "$#" -ge 2 ] || { echo "$usage" >&2; exit 2; }
            timeout=$2; shift 2 ;;
        --help|-h)
            echo "$usage"
            echo 'Requires Docker with Compose. Default: bundled Ollama and automatic model download.'
            echo 'Existing .env and lab/model volumes are preserved. --check changes nothing.'
            echo 'auto verifies NVIDIA Docker access on Linux/WSL2; otherwise CPU. cpu disables detection; nvidia requires a successful probe.'
            exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done
case "$gpu" in auto|cpu|nvidia) ;; *) echo '--gpu must be auto, cpu or nvidia.' >&2; exit 2 ;; esac
case "$timeout" in ''|*[!0-9]*) echo '--timeout must be a positive number of seconds.' >&2; exit 2 ;; esac
if [ "${#timeout}" -gt 6 ] || [ "$timeout" -le 0 ]; then echo '--timeout must be between 1 and 999999 seconds.' >&2; exit 2; fi

fail() { printf '\nERROR: %s\n' "$1" >&2; exit 1; }
command -v docker >/dev/null 2>&1 || fail 'Docker is not installed. Install/start Docker Desktop (https://docs.docker.com/desktop/) or Docker Engine + Compose on Linux, then rerun this script.'
docker compose version >/dev/null 2>&1 || fail 'Docker Compose is unavailable. Install the Compose plugin or update Docker Desktop. Use docker compose, not the legacy docker-compose command.'
engine_os=$(docker info --format '{{.OSType}}' 2>/dev/null) || fail 'Docker is not running or this account cannot access it. Start Docker Desktop/the Docker service and check docker info. On Windows use WSL2 with Docker Desktop integration.'
[ "$engine_os" = linux ] || fail 'This lab requires Linux containers. Switch Docker Desktop to Linux containers and rerun.'
for path in docker-compose.yml .env.example nginx.conf backend/Dockerfile frontend/index.html; do
    [ -f "$path" ] || fail "Missing project file: $path. Download the complete project, including backend and frontend."
done
docker compose config --quiet || fail 'Compose configuration is invalid. Check .env against .env.example.'
memory=$(docker info --format '{{.MemTotal}}' 2>/dev/null || true)
case "$memory" in ''|*[!0-9]*) ;; *)
    if [ "$memory" -lt 8589934592 ]; then
        echo 'NOTE: Docker has less than 8 GiB RAM available. The default model may run with limited headroom; larger models need more available RAM/VRAM. Ollama has no project-defined container memory cap.'
    fi ;;
esac
if [ "$check_only" = 1 ]; then
    echo 'Docker, Compose, Linux containers and project configuration: OK. No files or services changed.'
    echo 'GPU access is verified during installation; --check does not start a probe container or change the selected backend.'
    exit 0
fi
if [ -e .env ] || [ -L .env ]; then
    echo 'Keeping existing .env and lab/model volumes.'
else
    (umask 077; set -o noclobber; cat .env.example > .env) || fail 'Could not create .env. No existing configuration was overwritten.'
    echo 'Created .env from .env.example. Ollama runs inside Docker by default; no local Ollama or Python installation is required.'
fi
docker compose config --quiet || fail 'Compose configuration is invalid. Check .env.'

work=$(mktemp -d "${TMPDIR:-/tmp}/vulnlm-install.XXXXXX")
up_pid=''
up_done=0
probe_name=''
cleanup() {
    if [ -n "$probe_name" ]; then docker rm -f "$probe_name" >/dev/null 2>&1 || true; fi
    rm -f "$work/compose.log" "$work/gpu.log" "$work/override.yml"
    rmdir "$work" 2>/dev/null || true
}
interrupted() {
    if [ -n "$up_pid" ] && [ "$up_done" = 0 ]; then kill "$up_pid" 2>/dev/null || true; wait "$up_pid" 2>/dev/null || true; fi
    echo 'Stopped waiting. Lab/model volumes were not removed. Rerun this script to continue.' >&2
    exit 130
}
trap cleanup EXIT
trap interrupted INT TERM
started=$SECONDS
# Compose automatically loads this local override on subsequent starts/logs/stops.
# Never overwrite a user override or infer hardware from inside the app container.
override=docker-compose.override.yml
marker='# Generated by VulnLM installer: GPU selection. Do not edit; use --gpu.'
managed=0
if [ -f "$override" ] && [ "$(head -n 1 "$override")" = "$marker" ] && [ ! -L "$override" ]; then managed=1; fi
external=$(docker compose config --environment | awk '/^OLLAMA_URL=/{sub(/^OLLAMA_URL=/, ""); print; exit}')
custom_file=$(docker compose config --environment | awk '/^COMPOSE_FILE=/{sub(/^COMPOSE_FILE=/, ""); print; exit}')
backend=cpu
if [ -n "$custom_file" ] || [ -e compose.override.yaml ] || [ -e compose.override.yml ] || [ -e docker-compose.override.yaml ] || { { [ -e "$override" ] || [ -L "$override" ]; } && [ "$managed" = 0 ]; }; then
    [ "$gpu" = auto ] || fail 'Custom Compose files/override detected. GPU settings are user-managed; remove the custom selection before using --gpu.'
    echo 'Custom Compose files/override detected: preserving user-managed GPU configuration.'
elif [ -n "$external" ]; then
    [ "$gpu" != nvidia ] || fail 'Host/external Ollama is selected. Its GPU is managed on that host; --gpu nvidia applies only to bundled Ollama.'
    echo 'Host/external Ollama selected: keeping its GPU configuration; no bundled GPU probe.'
    # Remove only our old GPU settings, leaving the host preference unchanged.
    if [ "$managed" = 1 ]; then printf '%s\nservices: {}\n' "$marker" > "$override"; fi
else
    platform=$(uname -s)
    release=$(uname -r)
    case "$platform:$release" in
        Darwin:*) echo 'macOS: bundled Docker Ollama uses CPU. Optional host Ollama can use Apple GPU.' ;;
        Linux:*[Mm]icrosoft*|Linux:*WSL*) echo 'Windows/WSL2 detected: checking NVIDIA support.' ;;
        Linux:*) echo 'Linux detected: checking NVIDIA support.' ;;
        *) echo "Platform $platform: bundled Ollama uses CPU." ;;
    esac
    candidate=0
    if [ "$platform" = Linux ] && [ "$gpu" != cpu ]; then
        runtimes=$(docker info --format '{{json .Runtimes}}' 2>/dev/null || true)
        case "$runtimes" in *nvidia*) candidate=1 ;; esac
        if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1; then candidate=1; fi
        if [ -x /usr/lib/wsl/lib/nvidia-smi ] && /usr/lib/wsl/lib/nvidia-smi -L >/dev/null 2>&1; then candidate=1; fi
    fi
    if [ "$candidate" = 1 ] || { [ "$platform" = Linux ] && [ "$gpu" = nvidia ]; }; then
        echo 'Verifying NVIDIA access inside an isolated Docker probe (up to 60 seconds).'
        # Same pinned image as bundled Ollama. No lab volumes, ports or network access.
        probe_name="vulnlm-gpu-probe-$$"
        docker run --rm --name "$probe_name" --network none --gpus all --entrypoint nvidia-smi ollama/ollama:0.35.1 -L >"$work/gpu.log" 2>&1 &
        up_pid=$!
        probe_started=$SECONDS
        while kill -0 "$up_pid" 2>/dev/null && [ "$((SECONDS-probe_started))" -lt 60 ] && [ "$((SECONDS-started))" -lt "$timeout" ]; do sleep 1; done
        if kill -0 "$up_pid" 2>/dev/null; then
            kill "$up_pid" 2>/dev/null || true
            docker rm -f "$probe_name" >/dev/null 2>&1 || true
        fi
        if wait "$up_pid" && [ -s "$work/gpu.log" ] && LC_ALL=C grep -q 'GPU .*UUID:' "$work/gpu.log"; then backend=nvidia; fi
        up_pid=''
        docker rm -f "$probe_name" >/dev/null 2>&1 || true
        probe_name=''
        if [ "$backend" != nvidia ]; then
            echo 'NVIDIA Docker probe failed/timed out: using CPU. Check NVIDIA driver, Linux NVIDIA Container Toolkit or Windows WSL2/Docker Desktop GPU support.'
            tail -n 5 "$work/gpu.log" >&2
        fi
    fi
    [ "$gpu" != nvidia ] || [ "$backend" = nvidia ] || fail 'NVIDIA GPU was required but Docker access could not be verified. No services were started. Use --gpu cpu or fix the GPU prerequisites.'
    {
        printf '%s\n' "$marker"
        if [ "$backend" = nvidia ]; then
            cat <<'GPU_YAML'
services:
  ollama:
    deploy:
      resources:
        reservations:
          devices:
            - driver: nvidia
              count: all
              capabilities: [gpu]
GPU_YAML
        else
            echo 'services: {}'
        fi
    } > "$work/override.yml"
    mv "$work/override.yml" "$override"
    echo "Bundled Ollama backend: $backend (saved in $override). AMD/Intel GPUs currently use CPU."
fi
docker compose config --quiet || fail 'Selected GPU Compose configuration is invalid.'
[ "$((SECONDS-started))" -lt "$timeout" ] || fail 'Timed out during GPU verification. Rerun with a longer --timeout or --gpu cpu; lab data was kept.'
echo 'Building/starting the lab. First run downloads Docker images and the default model (about 1.9 GB); this can take several minutes.'
echo 'Bundled Ollama is the default. If you explicitly selected a host Ollama, it must be reachable; the gateway downloads a missing active model there.'
: > "$work/compose.log"
docker compose up --build -d >"$work/compose.log" 2>&1 &
up_pid=$!
last_progress=-10
ready=0
while [ "$((SECONDS-started))" -lt "$timeout" ]; do
    if [ "$up_done" = 0 ] && ! kill -0 "$up_pid" 2>/dev/null; then
        if wait "$up_pid"; then
            up_done=1
            # Nginx resolves the app hostname at startup; refresh it after recreation.
            docker compose restart edge >>"$work/compose.log" 2>&1 || fail 'Could not refresh the UI proxy. Check docker compose logs edge.'
        else
            up_done=1
            tail -n 35 "$work/compose.log" >&2
            docker compose ps --all >&2 || true
            fail 'Startup failed. Run: docker compose logs --tail 80 model-init model-gateway ollama app. Fix the reported error and rerun; do not delete volumes.'
        fi
    fi
    if [ "$up_done" = 1 ]; then
        # Python runs INSIDE the app container; the host does not need Python or curl.
        if status=$(docker compose exec -T app python -c '
import json, urllib.request, urllib.error
try:
    response = urllib.request.urlopen("http://edge:8080/ready", timeout=12)
except urllib.error.HTTPError as exc:
    response = exc
except OSError:
    print("Waiting for the app endpoint"); raise SystemExit(1)
try:
    data = json.load(response)
except (ValueError, OSError):
    print("Waiting for a valid readiness response"); raise SystemExit(1)
print(" / ".join(key + ": " + value for key, value in data.get("checks", {}).items()))
raise SystemExit(0 if data.get("status") == "ready" else 1)
' 2>/dev/null); then ready=1; break; fi
    else
        status='Starting services / downloading the initial model'
    fi
    elapsed=$((SECONDS-started))
    if [ "$((elapsed-last_progress))" -ge 10 ]; then
        printf '[%ss] %s\n' "$elapsed" "${status:-Waiting for services}"
        if [ "$up_done" = 0 ]; then tail -n 3 "$work/compose.log"; fi
        last_progress=$elapsed
    fi
    sleep 2
done
if [ "$ready" != 1 ]; then
    if [ "$up_done" = 0 ]; then kill "$up_pid" 2>/dev/null || true; wait "$up_pid" 2>/dev/null || true; fi
    tail -n 20 "$work/compose.log" >&2
    docker compose ps --all >&2 || true
    fail 'Timed out waiting for readiness. First downloads can be slow. Check: docker compose logs --tail 80 model-init model-gateway ollama app. For external Ollama, start it or clear OLLAMA_URL in .env to use bundled Ollama. Rerun with --timeout 3600; existing data/downloads are kept.'
fi
binding=$(docker compose port edge 8080 | head -n 1)
[ -n "$binding" ] || fail 'App is ready but no UI port was found. Check docker compose ps and docker compose logs edge.'
echo "Ready: $status"
printf 'Open the lab: http://%s\nSetup checks: http://%s/setup\n' "$binding" "$binding"
echo 'Use the Alice demo account on the sign-in screen. Stop the lab with: docker compose stop'
